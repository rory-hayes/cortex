const templatesById = new Map(
  setupPrFileTemplates.map((template) => [template.templateId, template]),
);

export const listSetupPrFileTemplates = (): SetupPrFileTemplate[] =>
  setupPrFileTemplates.map((template) => ({
    ...template,
    matchingValidationIds: [...template.matchingValidationIds],
    reviewInstructions: [...template.reviewInstructions],
  }));

export const renderSetupPrFileTemplate = (
  templateId: SetupPrTemplateId,
): RenderedSetupPrTemplateFile => {
  const template = templatesById.get(templateId);

  if (template === undefined) {
    throw new Error(`Unknown setup PR template: ${templateId}`);
  }

  return {
    ...template,
    content: renderers[template.templateId](),
    generatedBy: "cortex_setup_pr_template",
    matchingValidationIds: [...template.matchingValidationIds],
    reviewInstructions: [...template.reviewInstructions],
  };
};

export const buildSetupPrTemplateFilesForTask = (
  input: CortexTask,
): RenderedSetupPrTemplateFile[] => {
  const task = CortexTaskSchema.parse(input);

  if (task.executionMode !== "setup_pr" || task.riskLevel === "blocked") {
    return [];
  }

  const suggestedValidationIds = new Set(
    task.suggestedValidation.map((validation) => validation.validationId),
  );

  return setupPrFileTemplates
    .filter((template) =>
      template.matchingValidationIds.some((validationId) =>
        suggestedValidationIds.has(validationId),
      ),
    )
    .map((template) => renderSetupPrFileTemplate(template.templateId));
};
