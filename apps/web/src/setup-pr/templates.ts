export type SetupPrTemplateId =
  | "agent_instructions"
  | "architecture_doc"
  | "backlog"
  | "ci_workflow"
  | "contributing"
  | "integration_notes"
  | "product_spec"
  | "repo_policy";

type ReviewMarkerPlacement = "file_content" | "preview_metadata";

export type SetupPrFileTemplate = {
  label: string;
  matchingValidationIds: readonly string[];
  operation: "create_or_update";
  path: string;
  reviewInstructions: readonly string[];
  reviewMarkerPlacement: ReviewMarkerPlacement;
  reviewRequired: true;
  summary: string;
  templateId: SetupPrTemplateId;
};

export type RenderedSetupPrTemplateFile = SetupPrFileTemplate & {
  content: string;
  generatedBy: "cortex_setup_pr_template";
};

